import { describe, expect, it } from 'vitest';
import { createClassifier, isGeneratedText, languageOf } from '../src/core/scan/classify.ts';

const classify = (path: string, opts = {}) => {
  const file = createClassifier(opts).classify({ path, size: 1 });
  return file ? `${file.class} ${file.language}` : null;
};

describe('classification', () => {
  it.each([
    ['src/app.ts', 'code javascript'],
    ['src/App.tsx', 'code javascript'],
    ['main.py', 'code python'],
    ['cmd/main.go', 'code go'],
    ['config/app.yaml', 'config yaml'],
    ['settings.json', 'config json'],
    ['notebook.ipynb', 'code notebook'],
    ['infra/main.tf', 'config hcl'],
    ['pyproject.toml', 'config toml'],
    ['Dockerfile', 'code shell'],
    ['Dockerfile.prod', 'code shell'],
    ['Makefile', 'code shell'],
    ['.env', 'code shell'],
    ['.env.production', 'code shell'],
    ['scripts/deploy.sh', 'code shell'],
    ['Gemfile', 'code ruby'],
    ['infra/main.bicep', 'code bicep'],
    ['batch/requests.jsonl', 'config json'],
    ['data/events.ndjson', 'config json'],
    ['ci/Jenkinsfile', 'code java'],
    ['build.gradle', 'code java'],
    ['src/main/groovy/App.groovy', 'code java'],
    ['.envrc', 'code shell'],
    ['deploy/setup.ps1', 'code powershell'],
    ['Modules/Eval.psm1', 'code powershell'],
    ['public/index.html', 'code html'],
    ['src/App.vue', 'code html'],
    ['src/routes/+page.svelte', 'code html'],
    ['src/pages/index.astro', 'code html'],
    ['lua/plugin/init.lua', 'code lua'],
    ['analysis/fit.R', 'code r'],
    // Vendored and generated
    ['node_modules/x/index.js', 'vendored javascript'],
    ['web/vendor/lib.php', 'vendored php'],
    ['third_party/a.c', 'vendored c'],
    ['dist/bundle.js', 'vendored javascript'],
    ['static/app.min.js', 'vendored javascript'],
    ['package-lock.json', 'vendored json'],
    ['sub/poetry.lock', 'vendored null'],
    ['api/service.pb.go', 'generated go'],
    ['proto/x_pb2.py', 'generated python'],
    ['src/types.gen.ts', 'generated javascript'],
    ['web/.next/server/app/page.js', 'vendored javascript'],
    // A Next.js static export: its chunks are minified, but not named *.min.*.
    ['ui/out/_next/static/chunks/0-w0rr3df0htc.js', 'vendored javascript'],
    ['src/_next.ts', 'code javascript'],
    ['app/.svelte-kit/output/server/index.js', 'vendored javascript'],
    ['.vercel/output/functions/index.func/index.js', 'vendored javascript'],
    // Docs: no lexer, matched for mentions
    ['README.md', 'docs null'],
    ['docs/setup.py', 'docs null'],
    ['notes.txt', 'docs null'],
    ['guide.rst', 'docs null'],
    // A docs notebook keeps its language, so that only its cells are matched.
    ['docs/tour.ipynb', 'docs notebook'],
    // Tests are reported like code but tagged
    ['tests/test_app.py', 'test python'],
    ['src/app.test.ts', 'test javascript'],
    ['pkg/app_test.go', 'test go'],
    ['src/AppTest.java', 'test java'],
    ['spec/model_spec.rb', 'test ruby'],
    // Test directories in any case, test projects, and test data
    ['Tests/smoke.py', 'test python'],
    ['src/Connectors.OpenAI.UnitTests/TestData/chat.json', 'test json'],
    ['dotnet/IntegrationTests/AgentTests.cs', 'test csharp'],
    ['App/MyAppUITests/Launch.swift', 'test swift'],
    ['python/test_data/config.yaml', 'test yaml'],
    ['packages/openai/src/__fixtures__/response.json', 'test json'],
    ['web/src/__mocks__/client.ts', 'test javascript'],
    ['tests/Fixtures/a.json', 'test json'],
    ['examples/e2e/chat.ts', 'test javascript'],
    ['packages/ai/integration-tests/stream.ts', 'test javascript'],
    // …but not names that merely contain one
    ['src/Contest.java', 'code java'],
    ['src/contests/latest.py', 'code python'],
    ['src/ABTest/flags.ts', 'code javascript'],
    ['src/testing/fixture.ts', 'code javascript'],
    // No lexer
    ['image.png', 'code null'],
    ['LICENSE', 'code null'],
  ])('%s → %s', (path, expected) => {
    expect(classify(path)).toBe(expected);
  });

  it('applies include, exclude and overrides', () => {
    expect(classify('src/a.ts', { include: ['lib/**'] })).toBeNull();
    expect(classify('lib/a.ts', { include: ['lib/**'] })).toBe('code javascript');
    expect(classify('src/a.ts', { exclude: ['src/**'] })).toBeNull();
    expect(
      classify('examples/a.md', { overrides: [{ paths: ['examples/**'], class: 'code' }] }),
    ).toBe('code null');
    expect(
      classify('vendor/ours.go', { overrides: [{ paths: ['vendor/ours.go'], class: 'code' }] }),
    ).toBe('code go');
    expect(
      classify('tests/a.py', { overrides: [{ paths: ['tests/**'], class: 'vendored' }] }),
    ).toBe('vendored python');
  });

  it.each([
    ['// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: chat.proto\n', true],
    // Kubernetes puts it after the license header.
    [
      `/*\n${' * Licensed under the Apache License.\n'.repeat(12)}*/\n\n// Code generated by deepcopy-gen. DO NOT EDIT.\n`,
      true,
    ],
    ['# Code generated by datamodel-codegen. DO NOT EDIT.\n', true],
    ['// This file is @generated by prost-build.\n', true],
    ['/**\n * @generated SignedSource<<abc>>\n */\n', true],
    ['const marker = "// Code generated by x. DO NOT EDIT.";\n', false],
    ['// Code generated by hand, then edited.\n', false],
    ['@Generated("x")\nclass A {}\n', false],
    [`${'x\n'.repeat(2048)}// Code generated by x. DO NOT EDIT.\n`, false],
  ])('reads generated headers: %j', (text, generated) => {
    expect(isGeneratedText(text)).toBe(generated);
  });

  it('finds languages by name and extension', () => {
    expect(languageOf('a/b/CONTAINERFILE')).toBeNull();
    expect(languageOf('x.JSON')).toBe('json');
    expect(languageOf('.editorconfig')).toBe('ini');
    expect(languageOf('noext')).toBeNull();
    // Names that Object.prototype has aren't languages.
    for (const name of [
      'constructor',
      'toString',
      '__proto__',
      'a/x.constructor',
      'b.hasOwnProperty',
    ]) {
      expect(languageOf(name), name).toBeNull();
    }
  });
});
